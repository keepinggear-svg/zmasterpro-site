def main() -> None:
    data = json.loads(MENU.read_text(encoding="utf-8"))
    current = data["dishes"]
    if len(current) < 151:
        raise SystemExit(f"Expected at least 151 dishes, got {len(current)}")

    current = [item for item in current if item["id"] <= 151]
    for item in current:
        if item["category"] == "鱼虾与海鲜":
            item["category"] = "鱼虾蟹与水产"
        item["featured"] = False

    data["categoryOrder"] = [
        "全部",
        "主食与早餐",
        "猪肉与排骨",
        "牛肉与羊肉",
        "鸡肉与鸭肉",
        "鱼虾蟹与水产",
        "鸡蛋与豆腐",
        "蔬菜菌菇与薯类",
        "汤羹与瓦罐",
        "凉菜与小吃",
        "甜品与水果",
        "冬季温补",
    ]
    data["cuisineOrder"] = ["全部风味", "湘菜", "云贵川渝", "泰式", "韩式", "日式"]
    data["featuredIds"] = [153, 154, 155, 160, 163]
    data["dishes"] = current + NEW_DISHES
    for item in data["dishes"]:
        item["featured"] = item["id"] in data["featuredIds"]
    data["version"] = datetime.now(ZoneInfo("Asia/Shanghai")).isoformat(timespec="seconds")
    MENU.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Updated {MENU} to {len(data['dishes'])} dishes")


if __name__ == "__main__":
    main()
