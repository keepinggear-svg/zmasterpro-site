def dish(
    dish_id: int,
    name: str,
    category: str,
    audience: str,
    summary: str,
    duration: str,
    difficulty: str,
    ingredients: list[str],
    steps: list[str],
    tip: str,
    *,
    cuisine: str = "",
    aliases: list[str] | None = None,
) -> dict:
    record = {
        "id": dish_id,
        "name": name,
        "category": category,
        "audience": audience,
        "cuisine": cuisine,
        "seasonal": False,
        "featured": False,
        "image": f"/family-flavor/dishes/{dish_id:03d}.jpg",
        "summary": summary,
        "duration": duration,
        "difficulty": difficulty,
        "ingredients": ingredients,
        "steps": steps,
        "tip": tip,
    }
    if aliases:
        record["aliases"] = aliases
    return record


